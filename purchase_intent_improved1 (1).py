# STEP 2 — Imports
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import joblib
import warnings
warnings.filterwarnings("ignore")

from ucimlrepo import fetch_ucirepo
from imblearn.pipeline import Pipeline as ImbPipeline
from imblearn.over_sampling import SMOTENC
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate, cross_val_predict, RandomizedSearchCV
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, ExtraTreesClassifier, HistGradientBoostingClassifier
from sklearn.dummy import DummyClassifier
from sklearn.metrics import (accuracy_score, precision_score, recall_score, f1_score,
    roc_auc_score, classification_report, confusion_matrix, ConfusionMatrixDisplay, RocCurveDisplay, precision_recall_curve)

# STEP 3 — Load UCI Online Shoppers Purchasing Intention dataset
online_shoppers = fetch_ucirepo(id=468)
X = online_shoppers.data.features.copy()
y = online_shoppers.data.targets.iloc[:, 0].astype(int).copy()
df = X.copy()
df["Revenue"] = y

print("Dataset shape:", df.shape)
display(df.head())

"""## 1. Problem framing
The business goal is to identify sessions with purchase intent so an e-commerce business can prioritize helpful interventions. The target is `Revenue` (1 = purchase, 0 = no purchase). Since purchases are the minority class, we report Precision, Recall, F1-score and ROC-AUC in addition to Accuracy.
"""

# STEP 4 — Understand the data and target imbalance
print("Data types:")
display(df.dtypes.to_frame("dtype"))
print("\nMissing values:")
display(df.isnull().sum().to_frame("missing_values"))
print("\nTarget counts:")
display(df["Revenue"].value_counts().to_frame("count"))
print("\nTarget percentages:")
display((df["Revenue"].value_counts(normalize=True) * 100).round(2).to_frame("percentage"))

# STEP 5 — EDA: target distribution and useful numeric distributions
counts = df["Revenue"].value_counts().sort_index()
plt.figure(figsize=(5,4)); plt.bar(["No Purchase (0)", "Purchase (1)"], counts.values); plt.title("Target Distribution"); plt.ylabel("Sessions"); plt.show()

for col in ["ProductRelated_Duration", "BounceRates", "ExitRates", "PageValues"]:
    plt.figure(figsize=(6,3)); plt.hist(df[col].dropna(), bins=40); plt.title(col); plt.show()

print("Purchase rate:", round(df["Revenue"].mean()*100, 2), "%")

"""## 2. Important preprocessing correction
The columns `OperatingSystems`, `Browser`, `Region`, and `TrafficType` are numeric **codes for categories**, not continuous measurements. They must be one-hot encoded, not scaled as if (for example) browser code 4 were twice browser code 2. `Month`, `VisitorType`, and `Weekend` are categorical too.

We keep legitimate zeros: a zero can mean that a visitor did not view a page or that a measured value was zero. We do not delete or replace these valid observations.
"""

# STEP 6 — Train/test split (stratified)
X = df.drop(columns="Revenue").copy()
y = df["Revenue"].astype(int).copy()

# Explicitly mark all coded and text categories as categorical
categorical_features = [
    "Month", "OperatingSystems", "Browser", "Region",
    "TrafficType", "VisitorType", "Weekend"
]
numeric_features = [col for col in X.columns if col not in categorical_features]

# Ensure the category-coded columns are treated as categories by the encoder
for col in categorical_features:
    X[col] = X[col].astype("category")

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

print("Train:", X_train.shape, " Test:", X_test.shape)
print("Numeric features:", numeric_features)
print("Categorical features:", categorical_features)

# STEP 7 — Preprocessing pipeline
numeric_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False))
])

preprocessor = ColumnTransformer(
    transformers=[
        ("num", numeric_transformer, numeric_features),
        ("cat", categorical_transformer, categorical_features)
    ],
    remainder="drop"
)

# SMOTENC operates on the original mixed-type DataFrame BEFORE one-hot encoding
smotenc = SMOTENC(categorical_features=categorical_features, random_state=42)
print("Preprocessing and SMOTENC are ready.")

"""## 3. Model comparison
We compare Logistic Regression, Random Forest, Extra Trees, and HistGradientBoosting. Each model is evaluated with stratified 5-fold cross-validation. The resampling step, when used, happens **inside each fold** to prevent data leakage. We compare both the original training distribution and SMOTENC-resampled training folds.
"""

# STEP 8 — Define candidate models
from imblearn.over_sampling import SMOTE

# Standardize categorical columns to string/object dtypes to prevent pandas category-casting bugs in SimpleImputer
for col in categorical_features:
    X_train[col] = X_train[col].astype(str)
    X_test[col] = X_test[col].astype(str)

# Configure preprocessor to output standard NumPy arrays
preprocessor.set_output(transform="default")

models = {
    "Logistic Regression": LogisticRegression(max_iter=2500, class_weight="balanced"),
    "Random Forest": RandomForestClassifier(n_estimators=300, class_weight="balanced", random_state=42, n_jobs=-1),
    "Extra Trees": ExtraTreesClassifier(n_estimators=300, class_weight="balanced", random_state=42, n_jobs=-1),
    "Hist Gradient Boosting": HistGradientBoostingClassifier(max_iter=200, learning_rate=0.08, random_state=42)
}

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
scoring = {"roc_auc": "roc_auc", "f1": "f1", "precision": "precision", "recall": "recall"}
cv_rows = []

for model_name, model in models.items():
    for sampling in ["No Resampling", "SMOTE"]:
        steps = []
        if sampling == "SMOTE":
            if model_name == "Logistic Regression":
                current_model = LogisticRegression(max_iter=2500)
            elif model_name == "Random Forest":
                current_model = RandomForestClassifier(n_estimators=300, random_state=42, n_jobs=-1)
            elif model_name == "Extra Trees":
                current_model = ExtraTreesClassifier(n_estimators=300, random_state=42, n_jobs=-1)
            else:
                current_model = model
            # Apply SMOTE after preprocessor yields fully numeric/encoded features
            steps = [("preprocessor", preprocessor), ("smote", SMOTE(random_state=42)), ("model", current_model)]
        else:
            current_model = model
            steps = [("preprocessor", preprocessor), ("model", current_model)]

        pipe = ImbPipeline(steps=steps)
        scores = cross_validate(pipe, X_train, y_train, cv=cv, scoring=scoring, n_jobs=-1)
        cv_rows.append({
            "Model": model_name, "Sampling": sampling,
            "CV ROC-AUC": scores["test_roc_auc"].mean(),
            "CV F1": scores["test_f1"].mean(),
            "CV Precision": scores["test_precision"].mean(),
            "CV Recall": scores["test_recall"].mean()
        })

# Add a majority-class baseline (no resampling)
baseline_pipe = ImbPipeline([("preprocessor", preprocessor), ("model", DummyClassifier(strategy="most_frequent"))])
baseline_scores = cross_validate(baseline_pipe, X_train, y_train, cv=cv, scoring=scoring, n_jobs=-1)
cv_rows.append({
    "Model": "Dummy Baseline", "Sampling": "No Resampling",
    "CV ROC-AUC": baseline_scores["test_roc_auc"].mean(),
    "CV F1": baseline_scores["test_f1"].mean(),
    "CV Precision": baseline_scores["test_precision"].mean(),
    "CV Recall": baseline_scores["test_recall"].mean()
})

cv_results = pd.DataFrame(cv_rows).sort_values("CV ROC-AUC", ascending=False)
display(cv_results.round(4))

# STEP 9 — Fit and compare candidates on the untouched test set
# This table is for transparent comparison. Do not use the test set to tune parameters.
test_rows = []
fitted_candidates = {}

for model_name, model in models.items():
    for sampling in ["No Resampling", "SMOTENC"]:
        if sampling == "SMOTENC":
            if model_name == "Logistic Regression":
                current_model = LogisticRegression(max_iter=2500)
            elif model_name == "Random Forest":
                current_model = RandomForestClassifier(n_estimators=300, random_state=42, n_jobs=-1)
            elif model_name == "Extra Trees":
                current_model = ExtraTreesClassifier(n_estimators=300, random_state=42, n_jobs=-1)
            else:
                current_model = model
            pipe = ImbPipeline([
                ("smotenc", SMOTENC(categorical_features=categorical_features, random_state=42)),
                ("preprocessor", preprocessor), ("model", current_model)
            ])
        else:
            pipe = ImbPipeline([("preprocessor", preprocessor), ("model", model)])
        pipe.fit(X_train, y_train)
        pred = pipe.predict(X_test)
        prob = pipe.predict_proba(X_test)[:, 1]
        key = f"{model_name} | {sampling}"
        fitted_candidates[key] = pipe
        test_rows.append({
            "Model": model_name, "Sampling": sampling,
            "Accuracy": accuracy_score(y_test, pred),
            "Precision": precision_score(y_test, pred, zero_division=0),
            "Recall": recall_score(y_test, pred, zero_division=0),
            "F1": f1_score(y_test, pred, zero_division=0),
            "ROC-AUC": roc_auc_score(y_test, prob)
        })

# Add the majority-class baseline for reference
baseline_pipe = ImbPipeline([("preprocessor", preprocessor), ("model", DummyClassifier(strategy="most_frequent"))])
baseline_pipe.fit(X_train, y_train)
baseline_pred = baseline_pipe.predict(X_test)
baseline_prob = baseline_pipe.predict_proba(X_test)[:, 1]
test_rows.append({
    "Model": "Dummy Baseline", "Sampling": "No Resampling",
    "Accuracy": accuracy_score(y_test, baseline_pred),
    "Precision": precision_score(y_test, baseline_pred, zero_division=0),
    "Recall": recall_score(y_test, baseline_pred, zero_division=0),
    "F1": f1_score(y_test, baseline_pred, zero_division=0),
    "ROC-AUC": roc_auc_score(y_test, baseline_prob)
})

test_comparison = pd.DataFrame(test_rows).sort_values("ROC-AUC", ascending=False)
display(test_comparison.round(4))

"""## 4. Select and tune a model
Select the candidate with the best **cross-validation ROC-AUC** (not the best test score). Then tune that candidate using training data only. This avoids selecting a model based on repeated peeking at the test set.
"""

# STEP 10 — Select best pipeline type from cross-validation results
best_cv_row = cv_results.sort_values("CV ROC-AUC", ascending=False).iloc[0]
selected_name = best_cv_row["Model"]
selected_sampling = best_cv_row["Sampling"]
print("Selected using CV only:", selected_name, "|", selected_sampling)

if selected_name == "Logistic Regression":
    selected_model = LogisticRegression(max_iter=2500) if selected_sampling == "SMOTENC" else LogisticRegression(max_iter=2500, class_weight="balanced")
elif selected_name == "Random Forest":
    selected_model = RandomForestClassifier(random_state=42, n_jobs=-1) if selected_sampling == "SMOTENC" else RandomForestClassifier(class_weight="balanced", random_state=42, n_jobs=-1)
elif selected_name == "Extra Trees":
    selected_model = ExtraTreesClassifier(random_state=42, n_jobs=-1) if selected_sampling == "SMOTENC" else ExtraTreesClassifier(class_weight="balanced", random_state=42, n_jobs=-1)
else:
    selected_model = HistGradientBoostingClassifier(random_state=42)

steps = []
if selected_sampling == "SMOTENC":
    steps.append(("smotenc", SMOTENC(categorical_features=categorical_features, random_state=42)))
steps += [("preprocessor", preprocessor), ("model", selected_model)]
selected_pipeline = ImbPipeline(steps=steps)
print("Pipeline prepared for tuning.")

# STEP 11 — Hyperparameter tuning on training data only
if selected_name in ["Random Forest", "Extra Trees"]:
    params = {
        "model__n_estimators": [200, 300, 500],
        "model__max_depth": [None, 10, 20, 30],
        "model__min_samples_split": [2, 5, 10],
        "model__min_samples_leaf": [1, 2, 4],
        "model__max_features": ["sqrt", "log2"]
    }
elif selected_name == "Logistic Regression":
    params = {"model__C": [0.01, 0.1, 1, 10, 100]}
else:  # Hist Gradient Boosting
    params = {
        "model__learning_rate": [0.03, 0.05, 0.08, 0.1],
        "model__max_iter": [100, 200, 300],
        "model__max_leaf_nodes": [15, 31, 45],
        "model__l2_regularization": [0.0, 0.1, 1.0]
    }

search = RandomizedSearchCV(
    selected_pipeline, params, n_iter=8, scoring="roc_auc",
    cv=3, random_state=42, n_jobs=-1, verbose=1
)
search.fit(X_train, y_train)
final_model = search.best_estimator_
print("Best parameters:", search.best_params_)
print("Best CV ROC-AUC:", search.best_score_)

# STEP 12 — Choose a classification threshold using training data, then evaluate once on test data
# The default threshold is 0.50. We choose a threshold using out-of-fold TRAIN predictions only.
train_oof_prob = cross_val_predict(
    final_model, X_train, y_train, cv=cv, method="predict_proba", n_jobs=-1
)[:, 1]
precisions, recalls, thresholds = precision_recall_curve(y_train, train_oof_prob)
train_f1_scores = (2 * precisions[:-1] * recalls[:-1]) / (precisions[:-1] + recalls[:-1] + 1e-12)
best_threshold = thresholds[np.argmax(train_f1_scores)]
print("Selected threshold from training CV:", round(float(best_threshold), 3))

# Evaluate the untouched test set at the selected threshold
y_prob = final_model.predict_proba(X_test)[:, 1]
y_pred = (y_prob >= best_threshold).astype(int)

final_metrics = pd.DataFrame({
    "Metric": ["Accuracy", "Precision", "Recall", "F1-score", "ROC-AUC"],
    "Score": [
        accuracy_score(y_test, y_pred),
        precision_score(y_test, y_pred, zero_division=0),
        recall_score(y_test, y_pred, zero_division=0),
        f1_score(y_test, y_pred, zero_division=0),
        roc_auc_score(y_test, y_prob)
    ]
})
display(final_metrics)
print(classification_report(y_test, y_pred, zero_division=0))

print(final_model.steps[-1][1].__class__.__name__)

# STEP 13 — Confusion matrix and ROC curve
cm = confusion_matrix(y_test, y_pred)
ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=["No Purchase", "Purchase"]).plot()
plt.title("Final Model — Confusion Matrix")
plt.show()
RocCurveDisplay.from_predictions(y_test, y_prob)
plt.title("Final Model — ROC Curve")
plt.show()
print("Confusion matrix layout: [[TN, FP], [FN, TP]]")
