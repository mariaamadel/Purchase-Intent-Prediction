"""## 5. Business interpretation and limitations
- Higher Recall means the system catches more sessions that actually purchase, but may also create more false alarms.
- Higher Precision means a larger share of predicted buyers actually purchase.
- ROC-AUC measures ranking ability across thresholds; it is not the same as Accuracy.
- The positive class is the minority, so Accuracy alone is insufficient.
- SMOTENC is applied only to training folds/training data. The test set retains the original class distribution.
- The selected model is chosen by cross-validation, not by repeatedly optimizing against the test set.
"""

